"""Merge the AI (Claude) first-pass review of test_v6 into the review workbook.
Input : review/test_v6_review.xlsx (302 rows, generated by build_test_v6.py sheets)
        datasets/blade/processed/data_v6/review_ai/<project>_review.jsonl  (id, final_label, final_reason, note, changed, confidence)
Output: review/test_v6_review_reviewed.xlsx — '확정 label'/'확정 근거'/'비고(EXCLUDE + 사유)' filled, '담당자' = Claude(AI), original split kept in '원 배정',
        extra sheet '검수 메모' (reviewer, basis, counts). Human confirmation is still pending; freeze is a separate, user-approved step.
Usage: .python/python.exe -I scripts/merge_test_v6_ai_review.py [--date 2026-11-04]"""
from __future__ import annotations
import argparse, hashlib, json, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABELS = ['public', 'role_required', 'membership_required', 'tenant_match', 'owner_match', 'owner_or_admin', 'manual_review_required']
PROJECTS = ['seahub', 'redash', 'glitchtip', 'penpot']
SRC = ROOT / 'review/test_v6_review.xlsx'; DST = ROOT / 'review/test_v6_review_reviewed.xlsx'; RA = ROOT / 'datasets/blade/processed/data_v6/review_ai'
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main(date):
    from openpyxl import load_workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    rev = {}
    for p in PROJECTS:
        f = RA / f'{p}_review.jsonl'; assert f.exists(), f
        for line in f.read_text(encoding='utf-8').splitlines():
            if not line.strip(): continue
            r = json.loads(line); assert r['id'] not in rev, ('duplicate review', r['id']); r['_project'] = p; rev[r['id']] = r
    wb = load_workbook(SRC); ws = wb['test_v6_review']; h = {c.value: i + 1 for i, c in enumerate(ws[1])}
    c_id, c_rv, c_proj, c_draft = h['id'], h['담당자'], h['project'], h['초안 label']; c_final, c_reason, c_note = h['확정 label'], h['확정 근거'], h['비고(EXCLUDE + 사유)']
    c_orig = ws.max_column + 1; ws.cell(1, c_orig, '원 배정'); ws.cell(1, c_orig).font = Font(bold=True); ws.cell(1, c_orig).fill = PatternFill('solid', fgColor='DDEBF7')
    c_conf = c_orig + 1; ws.cell(1, c_conf, '확정 confidence(AI)'); ws.cell(1, c_conf).font = Font(bold=True); ws.cell(1, c_conf).fill = PatternFill('solid', fgColor='DDEBF7')
    ws.column_dimensions[ws.cell(1, c_orig).column_letter].width = 10; ws.column_dimensions[ws.cell(1, c_conf).column_letter].width = 10
    seen, stats = set(), dict(total=0, excluded=0, changed=0, final=Counter(), per_project=Counter(), excl_project=Counter(), changes=[], excludes=[])
    for row in range(2, ws.max_row + 1):
        rid = ws.cell(row, c_id).value
        if not rid: continue
        r = rev.get(rid); assert r, ('missing review', rid); assert r['_project'] == ws.cell(row, c_proj).value, rid; seen.add(rid)
        final, note, reason = (r.get('final_label') or '').strip(), (r.get('note') or '').strip(), (r.get('final_reason') or '').strip()
        excl = note.upper().startswith('EXCLUDE')
        assert (final == '') == excl, ('EXCLUDE <-> empty final mismatch', rid, final, note)
        assert excl or final in LABELS, (rid, final)
        ws.cell(row, c_orig, ws.cell(row, c_rv).value); ws.cell(row, c_rv, 'Claude(AI)')
        ws.cell(row, c_final, final); ws.cell(row, c_reason, reason); ws.cell(row, c_note, note); ws.cell(row, c_conf, r.get('confidence'))
        for c in (c_orig, c_conf, c_final, c_reason, c_note, c_rv): ws.cell(row, c).alignment = Alignment(wrap_text=True, vertical='top')
        draft, proj = ws.cell(row, c_draft).value, ws.cell(row, c_proj).value; stats['total'] += 1; stats['per_project'][proj] += 1
        if excl: stats['excluded'] += 1; stats['excl_project'][proj] += 1; stats['excludes'].append(dict(id=rid, project=proj, method=ws.cell(row, h['method']).value, path=ws.cell(row, h['path']).value, draft=draft, note=note))
        else:
            stats['final'][final] += 1
            if final != draft: stats['changed'] += 1; stats['changes'].append(dict(id=rid, project=proj, method=ws.cell(row, h['method']).value, path=ws.cell(row, h['path']).value, draft=draft, final=final))
    assert seen == set(rev), ('reviews without rows', set(rev) - seen)
    rate = stats['excluded'] / stats['total']
    memo = wb.create_sheet('검수 메모'); memo.column_dimensions['A'].width = 150
    for line in [f'검수자: Claude(AI) — 1차 확정 ({date}). 근거: controller_text 발췌 + 클론(datasets/blade/raw/opensource/test_v6_candidates) 직접 확인. 모델 예측은 어떤 것도 참조하지 않았다(test_v6 추론 금지).',
                 '상태: 사람 확인 전. 이 시트의 확정 label은 사람(사용자)이 확인·수정한 뒤에만 동결(build_test_v6.py freeze)에 쓴다. 담당자 열의 원래 층화 배정은 "원 배정" 열에 보존.',
                 '규칙: AGENTS.md data-v4 검수 규약 G1~G8 + 작업 S0 test_v6 보충 1~8(정지 지점 2 결정 포함). EXCLUDE는 G8(경계·의도 미확정·의도·구현 충돌·근거 누락)에만, manual은 G6 확실한 경우에만.',
                 f'건수: 총 {stats["total"]}, 확정 {stats["total"] - stats["excluded"]}, EXCLUDE {stats["excluded"]} ({rate:.1%}; 10% 초과 시 동결 전 중단), 초안 대비 변경 {stats["changed"]}.',
                 '확정 label 분포: ' + ', '.join(f'{k} {v}' for k, v in sorted(stats['final'].items(), key=lambda x: -x[1])),
                 '프로젝트별 EXCLUDE: ' + ', '.join(f'{p} {stats["excl_project"][p]}/{stats["per_project"][p]}' for p in PROJECTS),
                 '변경 목록(초안 → 확정):'] + [f'  {c["id"]}  {c["method"]} {c["path"]}  {c["draft"]} → {c["final"]}' for c in stats['changes']] + ['EXCLUDE 목록:'] + [f'  {e["id"]}  {e["method"]} {e["path"]}  (초안 {e["draft"]}) {e["note"]}' for e in stats['excludes']]:
        memo.append([line])
    wb.save(DST)
    out = dict(sheet=str(DST.relative_to(ROOT)).replace('\\', '/'), sha256=sha(DST), source_sheet_sha256=sha(SRC), reviewer='Claude(AI)', date=date, total=stats['total'], confirmed=stats['total'] - stats['excluded'],
               excluded=stats['excluded'], exclusion_rate=round(rate, 4), changed_from_draft=stats['changed'], final_labels=dict(stats['final']), per_project=dict(stats['per_project']), excluded_per_project=dict(stats['excl_project']),
               changes=stats['changes'], excludes=stats['excludes'])
    (RA / 'ai_review_report.json').write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
    print(json.dumps({k: v for k, v in out.items() if k not in ('changes', 'excludes')}, ensure_ascii=False))
    if rate > 0.10: print(f'WARNING exclusion rate {rate:.1%} > 10%: stop and report before freeze', file=sys.stderr)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--date', default='2026-11-04'); main(ap.parse_args().date)
